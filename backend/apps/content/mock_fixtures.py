"""Deterministic mock content drafts (always labelled as mock)."""

import json
import re
from typing import Any, cast

from apps.ai.prompting import extract_data_block
from apps.ai.providers.base import StructuredRequest
from apps.ai.providers.mock import register_mock_fixture

from .schemas import ContentBatchOutput, ContentDraft, FormatName, Platform, Slide

_TARGET = re.compile(
    r"^- (instagram|facebook|tiktok): (post|carousel|reel|story|short_video)$", re.M
)
_SINGLE = re.compile(r"Rewrite this as exactly one (instagram|facebook|tiktok) (\w+) draft")


def mock_content(request: StructuredRequest[Any]) -> ContentBatchOutput:
    context = json.loads(extract_data_block(request.prompt, "business_context") or "{}")
    name = context.get("business", {}).get("name") or "the business"
    brief = (extract_data_block(request.prompt, "owner_instructions") or "")[:80]
    targets = _TARGET.findall(request.prompt) or _SINGLE.findall(request.prompt)
    drafts = []
    for platform, fmt in targets:
        video = fmt in {"reel", "short_video"}
        slides = (
            [
                Slide(title="[Mock] Slide 1", body="Intro"),
                Slide(title="[Mock] Slide 2", body="Detail"),
            ]
            if fmt == "carousel"
            else []
        )
        drafts.append(
            ContentDraft(
                platform=cast(Platform, platform),
                format=cast(FormatName, fmt),
                title=f"[Mock] {brief or 'Post'} - {platform}",
                headline=f"[Mock] News from {name}",
                hook="[Mock] You'll want to see this.",
                caption=(
                    f"[Mock] {brief or 'Something new'} at {name}. "
                    "Placeholder text from the mock provider."
                ),
                cta="[Mock] Visit us this week.",
                hashtags=["mock", platform],
                script="[Mock] Shot 1: close-up. Shot 2: team smile." if video else "",
                slides=slides,
                creative_brief="[Mock] Bright natural-light photo of the product.",
                alt_text="[Mock] Product on a wooden counter.",
            )
        )
    return ContentBatchOutput(
        drafts=drafts, notes=["[Mock] Generated by the mock provider, not a real model."]
    )


register_mock_fixture(ContentBatchOutput, mock_content)
