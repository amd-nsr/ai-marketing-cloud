"""Deterministic mock content drafts (always labelled as mock)."""

import json
import re
from typing import Any, cast

from apps.ai.prompting import extract_data_block
from apps.ai.providers.base import StructuredRequest
from apps.ai.providers.mock import register_mock_fixture

from .schemas import (
    AssistOutput,
    ContentBatchOutput,
    ContentDraft,
    FormatName,
    Platform,
    Slide,
    StoryboardOutput,
    StoryboardScene,
)

_PLATFORMS = "instagram|facebook|tiktok|blog|email"
_TARGET = re.compile(
    rf"^- ({_PLATFORMS}): (post|carousel|reel|story|short_video|article|newsletter)$", re.M
)
_SINGLE = re.compile(rf"Rewrite this as exactly one ({_PLATFORMS}) (\w+) draft")
_OPERATION = re.compile(r"^Operation: (\w+)$", re.M)


def mock_content(request: StructuredRequest[Any]) -> ContentBatchOutput:
    context = json.loads(extract_data_block(request.prompt, "business_context") or "{}")
    name = context.get("business", {}).get("name") or "the business"
    brief = (extract_data_block(request.prompt, "owner_instructions") or "")[:80]
    targets = _TARGET.findall(request.prompt) or _SINGLE.findall(request.prompt)
    drafts = []
    for platform, fmt in targets:
        video = fmt in {"reel", "short_video"}
        slides = (
            [
                Slide(title="[Mock] Slide 1", body="Intro"),
                Slide(title="[Mock] Slide 2", body="Detail"),
            ]
            if fmt == "carousel"
            else []
        )
        drafts.append(
            ContentDraft(
                platform=cast(Platform, platform),
                format=cast(FormatName, fmt),
                title=f"[Mock] {brief or 'Post'} - {platform}",
                headline=f"[Mock] News from {name}",
                hook="[Mock] You'll want to see this.",
                caption=(
                    f"[Mock] {brief or 'Something new'} at {name}. "
                    "Placeholder text from the mock provider."
                ),
                cta="[Mock] Visit us this week.",
                hashtags=[] if platform in {"blog", "email"} else ["mock", platform],
                script="[Mock] Shot 1: close-up. Shot 2: team smile." if video else "",
                slides=slides,
                creative_brief="[Mock] Bright natural-light photo of the product.",
                alt_text="[Mock] Product on a wooden counter.",
            )
        )
    return ContentBatchOutput(
        drafts=drafts, notes=["[Mock] Generated by the mock provider, not a real model."]
    )


register_mock_fixture(ContentBatchOutput, mock_content)


def mock_assist(request: StructuredRequest[Any]) -> AssistOutput:
    text = (extract_data_block(request.prompt, "selected_text") or "").strip()
    match = _OPERATION.search(request.prompt)
    op = match.group(1) if match else "rewrite"
    if op == "draft":
        options = [f"[Mock draft {i}] Placeholder from the mock provider." for i in range(1, 4)]
    elif op == "alternatives":
        options = [f"[Mock alternative {i}] {text[:120]}" for i in range(1, 5)]
    elif op == "hashtags":
        options = [f"mock{i}" for i in range(1, 9)]
    elif op == "shorten":
        options = [f"[Mock shortened] {text[: max(len(text) // 2, 1)]}"]
    elif op == "expand":
        options = [f"[Mock expanded] {text} More detail would go here."]
    else:
        options = [f"[Mock {op}] {text}"]
    return AssistOutput(options=options, notes=["[Mock] Generated by the mock provider."])


def mock_storyboard(request: StructuredRequest[Any]) -> StoryboardOutput:
    return StoryboardOutput(
        title="[Mock] Storyboard",
        hook="[Mock] Close-up of the product in the first second.",
        scenes=[
            StoryboardScene(
                description=f"[Mock] Scene {i}",
                on_screen_text=f"[Mock] Point {i}",
                voiceover="",
                duration_seconds=3,
            )
            for i in range(1, 4)
        ],
        caption="[Mock] Caption for the video.",
        notes=["[Mock] Generated by the mock provider, not a real model."],
    )


register_mock_fixture(AssistOutput, mock_assist)
register_mock_fixture(StoryboardOutput, mock_storyboard)
