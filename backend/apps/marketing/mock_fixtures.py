"""Deterministic mock plans for tests and keyless development (always labelled as mock)."""

import json
from typing import Any

from apps.ai.prompting import extract_data_block
from apps.ai.providers.base import StructuredRequest
from apps.ai.providers.mock import register_mock_fixture

from .schemas import (
    Assumption,
    AudienceHypothesis,
    CalendarEntry,
    CampaignConcept,
    ChannelAllocation,
    ContentTheme,
    MarketingPlanOutput,
    MeasurementItem,
    Objective,
    Platform,
)

_PLATFORM_KEYS: dict[str, Platform] = {
    "Instagram": "instagram",
    "Facebook": "facebook",
    "TikTok": "tiktok",
}


def mock_plan(request: StructuredRequest[Any]) -> MarketingPlanOutput:
    raw = extract_data_block(request.prompt, "business_context") or "{}"
    context = json.loads(raw)
    name = context.get("business", {}).get("name") or "Your business"
    platforms = [
        _PLATFORM_KEYS[p]
        for p in context.get("platforms", {}).get("items", [])
        if p in _PLATFORM_KEYS
    ]
    platforms = platforms or ["instagram"]  # list[Platform]
    audiences = [a["name"] for a in context.get("audiences", {}).get("items", [])] or [
        "Local customers"
    ]
    weeks = 4
    for line in request.prompt.splitlines():
        if line.startswith("Plan horizon:"):
            weeks = int(line.split()[2])
    share = 100 // len(platforms)
    allocation = [
        ChannelAllocation(
            platform=p, share_percent=share, rationale=f"[Mock] Reach {audiences[0]} on {p}."
        )
        for p in platforms
    ]
    allocation[0].share_percent += 100 - share * len(platforms)
    days = ["Tue", "Thu", "Sat"]
    calendar = [
        CalendarEntry(
            week=w,
            day=days[(w + i) % 3],  # type: ignore[arg-type]
            platform=p,
            format="post" if i % 2 == 0 else "reel",
            theme="Behind the scenes" if w % 2 else "Customer stories",
            idea=f"[Mock] Week {w} idea for {name} on {p}.",
        )
        for w in range(1, weeks + 1)
        for i, p in enumerate(platforms)
    ]
    return MarketingPlanOutput(
        title=f"[Mock] {weeks}-week plan for {name}",
        summary=(
            f"[Mock] A deterministic placeholder plan for {name}. "
            "Generated without a real AI model."
        ),
        objectives=[
            Objective(
                title="Grow local awareness",
                description="[Mock] Become a familiar name with the primary audience.",
                metric="Profile visits",
                target="Directional increase versus the first week (hypothesis)",
                timeframe=f"{weeks} weeks",
            )
        ],
        audience_hypotheses=[
            AudienceHypothesis(
                audience=a,
                insight="[Mock] Responds to authentic, local content.",
                basis="user_provided",
            )
            for a in audiences[:2]
        ],
        content_themes=[
            ContentTheme(
                name="Behind the scenes",
                description="[Mock] How the work gets done.",
                example_ideas=["Morning prep"],
            ),
            ContentTheme(
                name="Customer stories",
                description="[Mock] Real customer moments (with consent).",
                example_ideas=["Regulars' favourites"],
            ),
        ],
        campaign_concepts=[
            CampaignConcept(
                name="Meet the team",
                objective="Grow local awareness",
                description="[Mock] Introduce the people behind the business.",
                platforms=platforms,
                duration_weeks=min(2, weeks),
                key_messages=["[Mock] Real people, real craft."],
            )
        ],
        channel_allocation=allocation,
        content_calendar=calendar,
        measurement=[
            MeasurementItem(metric="Reach", platform=p, why="[Mock] Indicates awareness.")
            for p in platforms
        ],
        assumptions=[
            Assumption(
                statement="[Mock] The team can post three times a week.", basis="ai_assumption"
            ),
        ],
        caveats=["[Mock] This plan was generated by the mock provider and is not real AI output."],
    )


register_mock_fixture(MarketingPlanOutput, mock_plan)
