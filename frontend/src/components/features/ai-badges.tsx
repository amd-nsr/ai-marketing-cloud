import { Badge } from "@/components/ui/badge";

/** Marks content produced by the mock provider so it is never mistaken for real AI output. */
export function MockAIBadge({ isMock }: { isMock: boolean }) {
  if (!isMock) return null;
  return (
    <Badge
      tone="warning"
      title="Generated by the built-in mock provider for development, not by a real AI model."
    >
      Mock AI output
    </Badge>
  );
}

export function AIGeneratedBadge({ model, isMock }: { model: string; isMock: boolean }) {
  if (isMock) return <MockAIBadge isMock />;
  return (
    <Badge tone="info" title={`Generated by ${model}. Review before using.`}>
      AI-generated · {model}
    </Badge>
  );
}
